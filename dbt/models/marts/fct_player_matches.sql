-- One row per player per fixture since 2016-17, including unused squad members
-- (0 minutes). FPL stats and price for every season; Opta detail from 2024-25.
-- `total_points` follows each season's own rules; model scoring *events* instead.
with fpl as (select * from {{ ref('int_player_matches') }}),
opta as (select * from {{ ref('stg_fpl_elo_insights__player_match_stats') }})

select
    fpl.player_match_key,
    fpl.match_key,
    fpl.season,
    fpl.gameweek,
    fpl.kickoff_utc,
    fpl.player_code,
    fpl.element,
    case fpl.element_type when 1 then 'GKP' when 2 then 'DEF' when 3 then 'MID' when 4 then 'FWD' end
        as position,
    fpl.team_key,
    fpl.opponent_team_key,
    fpl.is_home,
    fpl.is_provisional,

    fpl.minutes,
    fpl.starts,
    fpl.goals_scored,
    fpl.assists,
    fpl.clean_sheets,
    fpl.goals_conceded,
    fpl.own_goals,
    fpl.penalties_saved,
    fpl.penalties_missed,
    fpl.yellow_cards,
    fpl.red_cards,
    fpl.saves,
    fpl.bonus,
    fpl.bps,
    fpl.total_points,
    fpl.influence,
    fpl.creativity,
    fpl.threat,
    fpl.ict_index,
    fpl.expected_goals,
    fpl.expected_assists,
    fpl.expected_goal_involvements,
    fpl.expected_goals_conceded,
    fpl.tackles,
    fpl.clearances_blocks_interceptions,
    fpl.recoveries,
    fpl.defensive_contribution,

    fpl.value as price,
    fpl.selected,
    fpl.transfers_in,
    fpl.transfers_out,
    fpl.transfers_balance,

    opta.elo_match_id is not null as has_opta,
    opta.start_min,
    opta.finish_min,
    opta.opta_xg,
    opta.opta_xa,
    opta.opta_xgot,
    opta.total_shots,
    opta.shots_on_target,
    opta.big_chances_missed,
    opta.touches,
    opta.touches_opposition_box,
    opta.chances_created,
    opta.successful_dribbles,
    opta.accurate_passes,
    opta.final_third_passes,
    opta.accurate_crosses,
    opta.accurate_long_balls,
    opta.tackles_won,
    opta.interceptions,
    opta.opta_recoveries,
    opta.blocks,
    opta.clearances,
    opta.dribbled_past,
    opta.duels_won,
    opta.duels_lost,
    opta.aerial_duels_won,
    opta.was_fouled,
    opta.fouls_committed,
    opta.xgot_faced,
    opta.goals_prevented,
    opta.distance_covered,
    opta.top_speed
from fpl
left join opta
    on fpl.season = opta.season
    and fpl.element = opta.element
    and fpl.elo_match_id = opta.elo_match_id
