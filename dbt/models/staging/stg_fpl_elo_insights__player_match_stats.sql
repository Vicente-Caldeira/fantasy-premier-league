-- Opta-style per-player match stats. `player_id` is the season's FPL element id
-- (verified: 100% of rows match an FPL player-fixture and goals agree on 99.99%).
select
    season,
    player_id as element,
    match_id as elo_match_id,
    start_min,
    finish_min,
    minutes_played as opta_minutes,
    goals as opta_goals,
    xg as opta_xg,
    xa as opta_xa,
    xgot as opta_xgot,
    total_shots,
    shots_on_target,
    big_chances_missed,
    touches,
    touches_opposition_box,
    chances_created,
    successful_dribbles,
    accurate_passes,
    final_third_passes,
    accurate_crosses,
    accurate_long_balls,
    tackles_won,
    interceptions,
    recoveries as opta_recoveries,
    blocks,
    clearances,
    dribbled_past,
    duels_won,
    duels_lost,
    aerial_duels_won,
    was_fouled,
    fouls_committed,
    xgot_faced,
    goals_prevented,
    distance_covered,
    top_speed
from {{ source('fpl_elo_insights', 'player_match_stats') }}
